/// Occurrence counts of the tier-1 register, keyed on `(item, file)`. Counted
/// rather than collected so a row written twice is visible; a set would absorb
/// it and still look complete.
fn registered_counts() -> BTreeMap<(String, String), usize> {
    let mut counts: BTreeMap<(String, String), usize> = BTreeMap::new();
    for row in TIER_ONE {
        *counts
            .entry((row.item.to_string(), row.file.to_string()))
            .or_default() += 1;
    }
    counts
}

fn derived_counts(items: &[EligibleItem]) -> BTreeMap<(String, String), usize> {
    let mut counts: BTreeMap<(String, String), usize> = BTreeMap::new();
    for item in items {
        *counts
            .entry((item.item.clone(), item.file.clone()))
            .or_default() += 1;
    }
    counts
}

/// The comparison, with BOTH sides injected so a control can drive either leg
/// without writing into the source tree.
fn weld(
    derived: &BTreeMap<(String, String), usize>,
    registered: &BTreeMap<(String, String), usize>,
) -> Result<(), String> {
    if derived == registered {
        return Ok(());
    }
    let unregistered: Vec<&(String, String)> = derived
        .keys()
        .filter(|key| !registered.contains_key(*key))
        .collect();
    let stale: Vec<&(String, String)> = registered
        .keys()
        .filter(|key| !derived.contains_key(*key))
        .collect();
    // The two duplication sides are reported APART, because they are different
    // defects with different fixes and one message naming both sends the reader
    // to the wrong file. A duplicated REGISTERED key is one item enumerated
    // twice, so a reader has two reasons and no way to tell which is current. A
    // duplicated DERIVED key means the derivation produced one identity twice,
    // which is a derivation defect -- the identity renderer lost a
    // distinguishing part.
    let duplicated_registered: Vec<&(String, String)> = registered
        .iter()
        .filter(|(_, count)| **count > 1)
        .map(|(key, _)| key)
        .collect();
    let duplicated_derived: Vec<&(String, String)> = derived
        .iter()
        .filter(|(_, count)| **count > 1)
        .map(|(key, _)| key)
        .collect();
    Err(format!(
        "the cloak surface does not hold exactly the enumerated items. Eligible but unenumerated \
         (add each to TIER_ONE with its role, gate, and reason): {unregistered:?}. Enumerated but \
         absent from the surface: {stale:?}. Enumerated twice (one item, two rows -- delete one): \
         {duplicated_registered:?}. Derived twice (the derivation rendered one identity for two \
         items -- fix the renderer, not the register): {duplicated_derived:?}."
    ))
}

fn real_derived() -> BTreeMap<(String, String), usize> {
    let population = expect(cloak_population::read_population());
    derived_counts(&expect(eligible_items(&population)))
}

fn expect<T>(parsed: Result<T, String>) -> T {
    parsed.unwrap_or_else(|why| panic!("the cloak baseline cannot be evaluated: {why}"))
}

