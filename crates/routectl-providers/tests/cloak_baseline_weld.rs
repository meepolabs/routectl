/// What an eligible in-module item IS. The distinction is the point of putting
/// the orchestrator's own items in the population: an item classified
/// `Support` is asserted NOT to be a wire transform, so adding a transform
/// under that classification is a claim a reviewer can refuse.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Role {
    /// Mutates the outgoing wire body (or decides what the mutation is).
    Transform,
    /// Config, minting, telemetry, or the orchestrator itself: reaches the
    /// orchestrator's module but writes no transform of its own.
    Support,
}

/// One tier-1 row: an eligible item of the cloak surface, with the gate it
/// rides and, where the transform gives something up, the loss it takes.
struct TierOneRow {
    /// The item's identity within its file, exactly as the derivation renders
    /// it (`name` for a free function, `Type::method` for an associated one).
    item: &'static str,
    /// The file it lives in, relative to the crate's `src`.
    file: &'static str,
    role: Role,
    /// The predicate under which it runs, from the closed vocabulary below.
    gate: Gate,
    /// Why this row is what it claims to be, in terms a reader can check
    /// against the code.
    reason: &'static str,
    /// What the transform gives up when it fires, or `None` when it loses
    /// nothing. A `Transform` row with no loss is a legitimate shape (a rename
    /// preserves everything through the reverse map); the field exists so a
    /// loss cannot be silently absent.
    known_loss: Option<&'static str>,
}

