//! The CLOAK BASELINE weld: the credential-lane transform enumeration, welded
//! to the module surface where a derived side honestly exists and pinned by a
//! named register where it does not.
//!
//! Two tiers, and the ASYMMETRY between them is the first thing to read. It is
//! not an accident of effort -- it is the boundary between a population a
//! machine can enumerate and one only a reader can.
//!
//! # Tier 1 -- the in-module transforms, DERIVED and welded
//!
//! `anthropic_api/cloak.rs` plus the flat `anthropic_api/cloak/*.rs` are one
//! bounded surface, so the eligible items in them can be derived from a parse
//! (see `weld_support/cloak_population.rs` for the eligibility rule) and
//! compared against [`TIER_ONE`] by OCCURRENCE COUNT. That comparison is real
//! in both directions: an item added to the surface without joining the
//! register is red, and a register row whose item left the surface is red.
//!
//! ## What tier 1 adds over the compiler, and what it does not
//!
//! The compiler is still the pin for two of the three failure shapes. Delete a
//! transform and `cloak_oauth_egress` stops compiling; add one and never wire
//! it and `dead_code` fires. Neither of those needs a weld, and this weld does
//! not claim them.
//!
//! Its residual job is the ONE shape the compiler is blind to: a function that
//! is both ADDED and WIRED into the live path, which is neither dead nor
//! required by anything to join a hand-authored enumeration. That is the whole
//! ceiling of tier 1, and the internal baseline register restates it in the same
//! terms.
//!
//! Two structural choices follow from that job:
//!
//! - `cloak.rs` itself is IN the population, and its eligible non-transform
//!   items are classified as support/orchestrator in the same register. A
//!   population drawn from the leaf directory alone would let a transform
//!   written inline beside the orchestrator evade the weld entirely -- which is
//!   the easiest place to add one.
//! - the comparison is over occurrence COUNTS, not sets. A set absorbs a row
//!   listed twice and still looks complete, which is how one item can be
//!   classified under two contradictory reasons with nothing red.
//!
//! ## What tier 1 refuses rather than covers
//!
//! An item whose body a parse cannot see is refused, never skipped: any
//! item-position macro invocation, a `cfg_attr` that could inject a gate or a
//! path, an eligible function-pointer `const` or `static`. That last one is a
//! standing CEILING rather than a gap to close: a transform held in a value slot
//! is callable without being a function item, and following value initializers
//! through arbitrary expressions is a different program. Items generated by a
//! `derive` are outside the population by construction, for the same reason --
//! the derivation reads source before expansion.
//!
//! # Tier 2 -- the out-of-module transforms, CLAIMED and pinned, with no derived side
//!
//! The rest of the credential lane's transforms live in other modules and
//! another crate, each on its own gate predicate. There is no honest
//! tree-to-register derived side for them, and [`TIER_TWO`] does not pretend
//! otherwise: "every credential-lane transform wherever it lives" is a SEMANTIC
//! predicate, not a syntactic one. No parse decides whether a body or header
//! mutation is part of the cloak baseline.
//!
//! So what tier 2 enforces is the direction that IS checkable: every row it
//! claims is real -- its anchor resolves to a named item in the file it names,
//! its gate is in a closed vocabulary, its reason is checkable, and its pinning
//! test exists. It CANNOT prove no row is missing, and the register must never
//! be read as if it could.
//!
//! A partial scan of the lane-predicate call sites was considered as a derived
//! side and rejected: it would miss both new work inside an existing gate and
//! every always-on transform, while reading as completeness -- which is worse
//! than an honest absence, because a reader stops re-deriving what looks
//! already derived.
//!
//! `cloak_oauth_egress` itself is deliberately untouched by all of this. Its
//! transform order is load-bearing (the tool sort runs LAST so it orders the
//! final wire names) and its shapes are fixed from empirical capture, so the
//! enumeration is welded from the OUTSIDE rather than turned into a value the
//! live egress path folds over.

