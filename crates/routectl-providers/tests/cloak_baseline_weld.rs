    // swapping the map comparison for a key-set one passes every other test here
    // while letting one item be classified under two contradictory rows.
    //
    // And pins the SPLIT diagnostic, because the two sides are different defects
    // with different fixes: a duplicated register row is one item with two
    // reasons (delete a row), while a duplicated derived key means the identity
    // renderer lost a distinguishing part (fix the renderer). One combined
