/// The CLOSED gate vocabulary both registers draw from. Each variant spells the
/// predicate the code actually evaluates, including the asymmetries -- an
/// [`Gate::OauthBearerOnly`] transform is NOT the same population as an
/// [`Gate::OauthBearerAnthropicHost`] one, and normalizing the two to a tidy
/// "oauth lane" name would erase the very difference a reviewer needs to see.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
enum Gate {
    /// Runs on every cloaked request: past the forwarded-leg, auth-kind, host,
    /// `CloakMode::Never`, and identity gates, on both classification arms.
    CloakPathAlways,
    /// The cloaked path AND the non-CC classification arm.
    CloakPathNonCc,
    /// The cloaked path AND the non-CC arm AND the operator's tool-canonicalization
    /// switch left on.
    CloakPathNonCcNormalizeTools,
    /// The cloaked path, with a body effect only when the operator configured
    /// at least one tool rename.
    CloakPathOperatorRenames,
    /// The cloaked path, with a body effect only when the operator configured
    /// at least one sensitive word.
    CloakPathSensitiveWords,
    /// Provider construction / config deserialization, not a per-request path.
    ProviderConstruction,
    /// The lane predicate: OauthBearer auth kind AND exactly the
    /// `api.anthropic.com` host AND not the forwarded leg. Independent of the
    /// classification and of `CloakMode`.
    ///
    /// The two dispatch sites that spell those three terms INLINE rather than
    /// calling the lane helper ride this same variant: the predicate is what a
    /// gate identifies, and two extensionally identical predicates given two
    /// names would read as two different populations. Where a row's gate is
    /// evaluated is a fact about that row, so it lives in the row's reason.
    CloakLane,
    /// The lane predicate AND the non-CC classification arm.
    CloakLaneNonCc,
    /// The lane predicate AND the assembled body carrying the field the beta
    /// gates.
    CloakLaneBodyCarriesEffort,
    /// OauthBearer auth kind ALONE -- no host check, no forwarded-leg check.
    /// Deliberately spelled apart from its siblings: this asymmetry is the
    /// register's finding, not its tidy summary.
    OauthBearerOnly,
    /// OauthBearer auth kind AND exactly the `api.anthropic.com` host, with no
    /// forwarded-leg term.
    OauthBearerAnthropicHost,
    /// The forwarded-system-turn policy: this lane targets the Anthropic wire
    /// role AND a canonical system survived the billing filter, so the
    /// `role: "system"` turns ride in place rather than being lift-consumed.
    /// Not always-on -- with no canonical system the lift owns those turns and
    /// the screening pass never runs.
    ForwardedSystemTurnPolicy,
    /// No gate: runs on every request through the surface, cloak lane or not.
    AlwaysOn,
}

impl Gate {
    /// The vocabulary itself, content-pinned. Every variant here must be used
    /// by a row, and every row's gate must be here -- both directions are
    /// asserted, so an unused variant is a gate nothing rides and a new
    /// variant cannot be introduced without a row to justify it.
    const ALL: &'static [Self] = &[
        Self::CloakPathAlways,
        Self::CloakPathNonCc,
        Self::CloakPathNonCcNormalizeTools,
        Self::CloakPathOperatorRenames,
        Self::CloakPathSensitiveWords,
        Self::ProviderConstruction,
        Self::CloakLane,
        Self::CloakLaneNonCc,
        Self::CloakLaneBodyCarriesEffort,
        Self::OauthBearerOnly,
        Self::OauthBearerAnthropicHost,
        Self::ForwardedSystemTurnPolicy,
        Self::AlwaysOn,
    ];
}

/// The number of tier-2 rows, asserted exactly. This does not prove the
/// register is complete -- tier 2 has no derived side -- but it makes deleting
/// a reviewed row a named red build rather than a silent shrink.
const TIER_TWO_ROWS: usize = 12;

/// The number of DISTINCT gates the tier-2 rows ride, asserted exactly rather
/// than as a floor. A floor is satisfied by collapsing two asymmetric
/// predicates into one shared name, which is the specific erasure recording a
/// per-row gate exists to prevent -- and it is satisfied by adding a variant
/// nothing needed. Re-derive this when a row moves; do not widen it.
const TIER_TWO_DISTINCT_GATES: usize = 7;

/// The number of crates the tier-2 rows span, asserted exactly. Two: this
/// providers crate and the shared core identity module. `routectl-auth` carries
/// the OAuth provider definitions and no lane transform, so it is not one.
const TIER_TWO_CRATES: usize = 2;

/// One tier-2 row. NAMED fields rather than a positional tuple: seven
/// assertions below read these, and a positional swap of `reason` and `test`
/// would still typecheck while pointing every pin at prose.
struct TierTwoRow {
    /// The transform's operator-facing name, unique per file.
    transform: &'static str,
    /// The file it lives in, relative to its crate's `src`.
    file: &'static str,
    /// A NAMED function or const in `file` that the claim resolves against.
    /// Never a line number and never prose: both rot, and neither can be
    /// resolved by a test.
    anchor: &'static str,
    /// Which crate's `src` the file is relative to.
    crate_root: CrateRoot,
    gate: Gate,
    /// Why this is a credential-lane transform, in terms a reader can check.
    reason: &'static str,
    /// The test that pins this row's behavior. Resolved through the same
    /// bounded matcher the counter weld's register uses.
    test: &'static str,
    /// What the transform gives up, or `None` when it gives up nothing.
    known_loss: Option<&'static str>,
}

/// The crate a tier-2 row's file is relative to. Tier 2 spanning more than one
/// crate is half of why these transforms are easy to miss.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum CrateRoot {
    Providers,
    Core,
}

/// The sibling crate whose identity module holds two of the tier-2 anchors,
/// named rather than spelled inline so a rename of the crate directory fails at
/// one place with a diagnostic instead of at every row that reaches into it.
const CORE_CRATE_DIR: &str = "routectl-core";

impl CrateRoot {
    /// The crate's `src` directory, resolved from THIS crate's manifest dir and
    /// checked to exist. Self-diagnosing on purpose: a sibling path that does
    /// not resolve reports the path it tried, rather than surfacing later as
    /// "the anchor file is unreadable" and sending the reader to the row.
    fn src(self) -> Result<std::path::PathBuf, String> {
        let path = match self {
            Self::Providers => src_root(),
            Self::Core => std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
                .parent()
                .ok_or_else(|| {
                    "this crate's manifest dir has no parent, so the workspace's crate directory \
                     cannot be located"
                        .to_string()
                })?
                .join(CORE_CRATE_DIR)
                .join("src"),
        };
        if !path.is_dir() {
            return Err(format!(
                "{} is not a readable directory, so no row anchored in it can be resolved; the \
                 sibling-crate layout this register assumes has changed",
                path.display()
            ));
        }
        Ok(path)
    }
}

